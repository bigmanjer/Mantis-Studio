// Turns the original MANTIS literary library (Markdown) into searchable entries for the web app.
// Run from web/:  node scripts/build-knowledge-base.mjs
import fs from "node:fs";

const SRC = "../app/data/knowledge_base/mantis_literary_master_knowledge_base.md";
const OUT = "src/data/knowledge-builtin.ts";

const PREFIX = [
  ["Author biography:", "author"],
  ["Work reference:", "work"],
  ["Workflow checklist:", "revision"],
  ["Genre/form:", "genre"],
  ["Style notes:", "craft"],
  ["Literary period:", "period"],
  ["Theme:", "theme"],
];

const md = fs.readFileSync(SRC, "utf8").replace(/\r\n/g, "\n");
let section = "";
const entries = [];
const authors = new Map();

for (const raw of md.split("\n")) {
  const line = raw.trim();
  if (!line) continue;
  if (line.startsWith("#")) {
    section = line.replace(/^#+\s*/, "");
    continue;
  }
  if (!section || /^Built-in reference edition/i.test(line) || section.startsWith("MANTIS Literary")) continue;
  const hit = PREFIX.find(([p]) => line.startsWith(p));
  const category = hit ? hit[1] : /theme|motif/i.test(section) ? "theme" : /character/i.test(section) ? "character" : /world/i.test(section) ? "worldbuilding" : /dialogue/i.test(section) ? "dialogue" : /plot|scene/i.test(section) ? "plot" : "craft";
  entries.push({ s: section, c: category, t: line });

  // Author craft profiles: "Author biography: NAME[, note]. Major works: X. Useful for Y."
  const m = /^Author biography:\s*(.+?)(?:,[^.]*)?\.\s*Major works:\s*(.+?)\.\s*Useful for\s*(.+?)\.?$/i.exec(line);
  if (m) {
    const name = m[1].trim();
    const prev = authors.get(name.toLowerCase());
    const traits = m[3].trim().replace(/\.$/, "");
    if (prev) {
      const merged = [...new Set([...prev.traits.split(/,\s*(?:and\s+)?/), ...traits.split(/,\s*(?:and\s+)?/)].map((t) => t.trim()).filter(Boolean))];
      prev.traits = merged.join(", ");
      if (m[2].length > prev.works.length) prev.works = m[2].trim();
    } else {
      authors.set(name.toLowerCase(), { name, works: m[2].trim(), traits });
    }
  }
}

const out = `// Generated by scripts/build-knowledge-base.mjs from the original MANTIS literary library. Do not edit by hand.
// Original reference material: craft notes, genre patterns, and author craft profiles (influence traits, not imitation).
import "server-only";

export interface BuiltinEntry {
  /** Section heading. */
  s: string;
  /** Category. */
  c: string;
  /** Text. */
  t: string;
}

export interface AuthorLens {
  name: string;
  works: string;
  traits: string;
}

export const BUILTIN_ENTRIES: BuiltinEntry[] = ${JSON.stringify(entries)};

export const AUTHOR_LENSES: AuthorLens[] = ${JSON.stringify([...authors.values()].sort((a, b) => a.name.localeCompare(b.name)))};
`;
fs.mkdirSync("src/data", { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`${entries.length} entries, ${authors.size} author lenses -> ${OUT}`);
